// Local E2E setup for the NAS artifact flow — HTTP on localhost, no Cloudflare/NS needed.
// Generates an Ed25519 keypair + shared secrets, writes an agent run script, and prints the app
// env block to paste into .env.local. The app SIGNS with the private key; the agent VERIFIES with
// the public key — exactly like production, just over HTTP.
//
// Run:  node scripts/nas-local-e2e-setup.mjs
//
// Then: 1) paste the printed block into work-os/.env.local
//       2) bash nas-poc/agent/run-local.sh     (agent on :8080 LAN / :8081 "tunnel")
//       3) pnpm dev                              (restart to load .env.local)

import { generateKeyPairSync, randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const kid = "local-1";
const root = process.cwd();
const keysDir = path.resolve(root, "nas-poc/keys");
const storeDir = path.resolve(root, "nas-poc/local-store");
fs.mkdirSync(keysDir, { recursive: true });
fs.mkdirSync(storeDir, { recursive: true });

const { publicKey, privateKey } = generateKeyPairSync("ed25519");
const publicPem = publicKey.export({ type: "spki", format: "pem" }).toString();
const privatePem = privateKey.export({ type: "pkcs8", format: "pem" }).toString();
fs.writeFileSync(path.join(keysDir, `${kid}.private.pem`), privatePem, { mode: 0o600 });
fs.writeFileSync(path.join(keysDir, `${kid}.public.pem`), publicPem);

const finalizeSecret = randomBytes(24).toString("hex");
const sharePepper = randomBytes(24).toString("hex");
const tokenPublicKeys = JSON.stringify([{ kid, publicKeyPem: publicPem }]);
const signingKeyEnv = privatePem.replace(/\n/g, "\\n"); // single-line for .env (app un-escapes)

const appUrl = "http://localhost:3000";
const lanUrl = "http://localhost:8080";
const tunnelUrl = "http://localhost:8081";

const runSh = `#!/usr/bin/env bash
# Generated by scripts/nas-local-e2e-setup.mjs — runs the agent locally over HTTP (no TLS/tunnel).
# gitignored (contains FINALIZE_SECRET). Re-run the setup script to regenerate.
set -euo pipefail
cd "$(dirname "$0")"
export NAS_ROOT="${storeDir}"
export TOKEN_PUBLIC_KEYS='${tokenPublicKeys}'
export CLOUD_FINALIZE_URL="${appUrl}/api/artifacts/finalize"
export FINALIZE_SECRET="${finalizeSecret}"
export ALLOWED_ORIGIN="${appUrl}"
export POC_HASH_MODE=inline
export LAN_PORT=8080
export TUNNEL_PORT=8081
export AGENT_ID=local-agent
echo "agent: LAN ${lanUrl} · tunnel ${tunnelUrl} · store ${storeDir}"
exec npx tsx src/server.ts
`;
fs.writeFileSync(path.resolve(root, "nas-poc/agent/run-local.sh"), runSh, { mode: 0o755 });

const appEnv = `# --- NAS local E2E (paste into work-os/.env.local, then restart pnpm dev) ---
NAS_TOKEN_SIGNING_KEY="${signingKeyEnv}"
NAS_TOKEN_KID=${kid}
NAS_TOKEN_ISSUER=work-os
NAS_FINALIZE_SECRET=${finalizeSecret}
SHARE_TOKEN_PEPPER=${sharePepper}
NAS_AGENT_URL_LAN=${lanUrl}
NAS_AGENT_URL_TUNNEL=${tunnelUrl}
NAS_SHARE_BASE_URL=${appUrl}/api/artifacts/share
NAS_SMB_HOST=localhost
NAS_SMB_SHARE=WorkOS-Local
NEXT_PUBLIC_NAS_AGENT_URL_LAN=${lanUrl}
NEXT_PUBLIC_NAS_AGENT_URL_TUNNEL=${tunnelUrl}`;

console.log("✔ Setup do E2E local gerado.\n");
console.log(`  chaves: nas-poc/keys/${kid}.{private,public}.pem   (gitignored)`);
console.log(`  store:  ${path.relative(root, storeDir)}/           (arquivos enviados)`);
console.log(`  agente: nas-poc/agent/run-local.sh\n`);
console.log("1) Cole no work-os/.env.local:\n");
console.log(appEnv);
console.log("\n2) Suba o agente:   bash nas-poc/agent/run-local.sh");
console.log("3) Suba o app:      pnpm dev   (reinicie para carregar o .env.local)");
console.log(
  "4) Na tela: cadastre um Propósito (Admin), habilite NAS no projeto (campanha), e use 'Upload NAS' numa demanda."
);
